from bert_score import score
from typing import List

def evaluate_bertscore(generated_text: str, expected_answer: str) -> float:
    """
    Evaluates the semantic similarity of the generated text to the expected answer using BERTScore.
    
    Args:
        generated_text (str): The text generated by the chatbot.
        expected_answer (str): The expected, human-written answer.
        
    Returns:
        float: The F1 score from BERTScore, ranging from 0.0 to 1.0.
    """
    # Handle cases where the input strings are empty
    if not generated_text or not expected_answer:
        return 0.0
    
    # The 'bert_score' library expects inputs as lists of strings
    references = [expected_answer]
    predictions = [generated_text]

    try:
        # Run the BERTScore evaluation using the `bert_score.score` function.
        # This function downloads the model automatically.
        _, _, F1 = score(predictions, references, lang="en", verbose=False)
        
        # The F1 score is a tensor. We extract the value and convert it to a float.
        return F1.mean().item()
        
    except Exception as e:
        # If the compute function or model loading fails, return a default score.
        print(f"BERTScore computation failed with an error: {e}. Returning 0.0.")
        return 0.0
